#!/usr/bin/env python3
"""
sync_to_libraries.py - Synchronizes Skipo base assets into the host codebase's src/libraries/ folder.
Pure Python 3 standard library ONLY - zero pip dependencies.

Enforces Governance Law L20 (Skipo Isolation & Library Hydration):
- Applications MUST NOT import directly from the root Skipo/ directory.
- When root Skipo/ is updated, this script copies base primitives and assets into src/libraries/skipo/.
- Automatically scans src/ to detect (and optionally auto-fix) forbidden direct Skipo imports.
"""

from pathlib import Path
from typing import List, Dict, Tuple
import argparse
import os
import re
import shutil
import sys
import time

HERE = Path(__file__).resolve().parent
SKIPO_ROOT = HERE.parent

DIRECT_SKIPO_IMPORT_PATTERN = re.compile(
    r"""(?:from|import)\s+['"](?:@/|\.{1,2}/)*Skipo(?:/|['"])(?:packages/)?([^'"]*)['"]"""
)

def find_target_project(given_target: str) -> Path:
    """Resolve the host project root containing src/."""
    target = Path(given_target).resolve() if given_target else Path.cwd().resolve()
    
    # If target is inside Skipo, attempt to resolve parent repository
    if target == SKIPO_ROOT or (target / "Skipo").is_dir():
        if (target / "src").is_dir() and target != SKIPO_ROOT:
            return target
        if (SKIPO_ROOT.parent / "src").is_dir():
            return SKIPO_ROOT.parent

    # Check if target itself has src/
    if (target / "src").is_dir():
        return target

    # Fallback to current target
    return target

def sync_assets(target_root: Path, dry_run: bool = False) -> Tuple[int, List[str]]:
    """Copies packages from Skipo/packages into target_root/src/libraries/skipo."""
    copied_count = 0
    messages: List[str] = []
    
    lib_dir = target_root / "src" / "libraries" / "skipo"
    packages_dir = SKIPO_ROOT / "packages"

    if not packages_dir.is_dir():
        messages.append(f"[ERROR] Skipo packages directory not found at {packages_dir}")
        return 0, messages

    targets_to_sync = [
        ("ui/src", "ui"),
        ("backend/src", "backend"),
        ("systems/src", "systems"),
    ]

    for src_subpath, dest_subname in targets_to_sync:
        src_path = packages_dir / src_subpath
        if not src_path.is_dir():
            continue

        dest_path = lib_dir / dest_subname
        messages.append(f"Synchronizing {src_path.relative_to(SKIPO_ROOT)} -> {dest_path.relative_to(target_root)}")

        if not dry_run:
            if dest_path.exists():
                shutil.rmtree(dest_path)
            dest_path.mkdir(parents=True, exist_ok=True)

        for root, dirs, files in os.walk(src_path):
            # Ignore test files and temp directories
            dirs[:] = [d for d in dirs if d not in ("__tests__", "node_modules", "dist", ".turbo")]
            rel_root = Path(root).relative_to(src_path)
            target_sub = dest_path / rel_root

            if not dry_run and not target_sub.exists():
                target_sub.mkdir(parents=True, exist_ok=True)

            for f in files:
                if f.endswith((".ts", ".tsx", ".css", ".json", ".d.ts")) and not f.endswith((".test.ts", ".test.tsx", ".spec.ts")):
                    source_file = Path(root) / f
                    destination_file = target_sub / f
                    copied_count += 1
                    if not dry_run:
                        shutil.copy2(source_file, destination_file)

    # Generate src/libraries/skipo/index.ts
    skipo_index = lib_dir / "index.ts"
    skipo_index_content = """// ══════════════════════════════════════════════════════════════════════════════
// SKIPO BASE ASSET LIBRARY FACADE (L20 Compliance)
// Auto-generated by Skipo scripts/sync_to_libraries.py
// ══════════════════════════════════════════════════════════════════════════════

export * from './ui/index';
export * from './backend/index';
"""
    if not dry_run:
        lib_dir.mkdir(parents=True, exist_ok=True)
        skipo_index.write_text(skipo_index_content, encoding="utf-8")
        messages.append(f"Generated {skipo_index.relative_to(target_root)}")

    # Ensure src/libraries/index.ts exports ./skipo/index
    root_lib_index = target_root / "src" / "libraries" / "index.ts"
    reexport_line = "export * from './skipo/index';"
    if not dry_run:
        if root_lib_index.exists():
            existing_content = root_lib_index.read_text(encoding="utf-8")
            if reexport_line not in existing_content:
                updated_content = existing_content.rstrip() + f"\n{reexport_line}\n"
                root_lib_index.write_text(updated_content, encoding="utf-8")
                messages.append(f"Appended Skipo re-export to {root_lib_index.relative_to(target_root)}")
        else:
            root_lib_index.parent.mkdir(parents=True, exist_ok=True)
            root_lib_index.write_text(f"{reexport_line}\n", encoding="utf-8")
            messages.append(f"Created {root_lib_index.relative_to(target_root)}")

    return copied_count, messages

def scan_and_fix_imports(target_root: Path, auto_fix: bool = False) -> List[Dict[str, str]]:
    """Scans target src/ for direct imports from root Skipo and optionally auto-fixes them."""
    violations = []
    src_dir = target_root / "src"
    if not src_dir.is_dir():
        return violations

    for root, dirs, files in os.walk(src_dir):
        dirs[:] = [d for d in dirs if d not in ("node_modules", ".next", "dist", "skipo")]
        for f in files:
            if not f.endswith((".ts", ".tsx", ".js", ".jsx")):
                continue

            file_path = Path(root) / f
            try:
                content = file_path.read_text(encoding="utf-8")
            except Exception:
                continue

            matches = list(DIRECT_SKIPO_IMPORT_PATTERN.finditer(content))
            if matches:
                for m in matches:
                    violations.append({
                        "file": str(file_path.relative_to(target_root)),
                        "line": content[:m.start()].count("\n") + 1,
                        "raw": m.group(0),
                        "subpath": m.group(1) or ""
                    })

                if auto_fix:
                    # Replace direct Skipo import with @/libraries/skipo
                    def _repl(match):
                        sub = match.group(1) or ""
                        if sub.startswith("/"): sub = sub[1:]
                        if not sub:
                            return "from '@/libraries/skipo'"
                        return f"from '@/libraries/skipo/{sub}'"

                    fixed_content = DIRECT_SKIPO_IMPORT_PATTERN.sub(_repl, content)
                    file_path.write_text(fixed_content, encoding="utf-8")

    return violations

def main():
    parser = argparse.ArgumentParser(description="Synchronize Skipo base assets into src/libraries/skipo")
    parser.add_argument("target", nargs="?", default="", help="Target project root directory containing src/")
    parser.add_argument("--dry-run", action="store_true", help="Preview sync operations without writing")
    parser.add_argument("--auto-fix", action="store_true", help="Automatically rewrite direct Skipo imports to @/libraries/skipo")
    parser.add_argument("--strict", action="store_true", help="Exit with code 1 if direct Skipo imports are found")
    args = parser.parse_args()

    target_root = find_target_project(args.target)
    print("=" * 80)
    print(f"  SKIPO BASE ASSET LIBRARY SYNCHRONIZATION (L20)")
    print(f"  Source (Skipo):  {SKIPO_ROOT}")
    print(f"  Target Project:  {target_root}")
    print("=" * 80)

    start_time = time.time()
    copied, messages = sync_assets(target_root, dry_run=args.dry_run)
    for msg in messages:
        print(f"  ✔ {msg}")

    # Scan for forbidden direct Skipo imports
    violations = scan_and_fix_imports(target_root, auto_fix=args.auto_fix)
    
    duration = (time.time() - start_time) * 1000
    print("-" * 80)
    print(f"  Synchronized: {copied} assets into src/libraries/skipo ({duration:.1f}ms)")

    if violations:
        if args.auto_fix:
            print(f"  ✔ Auto-fixed {len(violations)} direct Skipo imports to use '@/libraries/skipo'")
        else:
            print(f"  🚨 Detected {len(violations)} direct Skipo import violations:")
            for v in violations:
                print(f"     - {v['file']}:{v['line']} -> {v['raw']}")
            print(f"  💡 Run with '--auto-fix' to convert them automatically to '@/libraries/skipo'")
            if args.strict:
                sys.exit(1)

    print("=" * 80 + "\n")

if __name__ == "__main__":
    main()
