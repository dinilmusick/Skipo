"""Fail-closed staged repair transactions (standalone; no CLI integration).

The existing main-branch reconciler is evaluated only against an isolated copy.
Only explicitly owned generated bytes, registry-approved retirements, and Skipo
state/manifest changes may cross the commit boundary. Unrecognized source edits
(including dependency migration source transformations) are blocked for review.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import stat
import tempfile
from pathlib import Path, PurePosixPath
from typing import Any, Callable

IGNORED = frozenset({".git", "node_modules", ".next", ".turbo", "dist", "build", ".cache", "__pycache__"})
STATE_FILES = frozenset({
    "package.json", ".skipo/project.json", ".skipo/dependencies.json",
    ".skipo/capabilities.json", ".skipo/overrides.json", ".skipo/migration-state.json",
})


class UnsafeRepair(ValueError):
    """A preflight invariant could not be established."""


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def canonical(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()


def relative_path(relative: str) -> tuple[str, ...]:
    if not isinstance(relative, str) or not relative or "\\" in relative or "\x00" in relative:
        raise UnsafeRepair(f"Unsafe path: {relative!r}")
    parsed = PurePosixPath(relative)
    if parsed.is_absolute() or any(x in (".", "..", "") for x in relative.split("/")):
        raise UnsafeRepair(f"Unsafe path: {relative!r}")
    if relative != parsed.as_posix():
        raise UnsafeRepair(f"Noncanonical path: {relative!r}")
    return parsed.parts


def checked(root: Path, relative: str) -> Path:
    parts = relative_path(relative)
    path = root
    for part in parts:
        path = path / part
        if path.is_symlink():
            raise UnsafeRepair(f"Symlink in repair path: {relative}")
    return path


def inventory(root: Path) -> dict[str, dict[str, Any]]:
    """Record bytes, mode and type of every relevant input without following links."""
    if root.is_symlink() or not root.is_dir():
        raise UnsafeRepair("Repair root must be an actual directory")
    result: dict[str, dict[str, Any]] = {}
    for base, directories, names in os.walk(root, followlinks=False):
        base_path = Path(base)
        kept = []
        for name in sorted(directories):
            if name in IGNORED:
                continue
            path = base_path / name
            relative = path.relative_to(root).as_posix()
            relative_path(relative)
            mode = path.lstat().st_mode
            if not stat.S_ISDIR(mode):
                raise UnsafeRepair(f"Unsafe directory entry: {relative}")
            kept.append(name)
        directories[:] = kept
        for name in sorted(names):
            path = base_path / name
            relative = path.relative_to(root).as_posix()
            relative_path(relative)
            metadata = path.lstat()
            if not stat.S_ISREG(metadata.st_mode):
                raise UnsafeRepair(f"Non-regular file or symlink: {relative}")
            raw = path.read_bytes()
            result[relative] = {
                "sha256": digest(raw), "size": len(raw), "mode": stat.S_IMODE(metadata.st_mode),
            }
    return dict(sorted(result.items()))


def _copy_project(root: Path, destination: Path) -> None:
    shutil.copytree(root, destination, symlinks=False, ignore=lambda _, names: [
        name for name in names if name in IGNORED
    ])


def _json(root: Path, relative: str) -> dict[str, Any]:
    file = checked(root, relative)
    if not file.is_file():
        return {}
    value = json.loads(file.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise UnsafeRepair(f"Expected JSON object: {relative}")
    return value


def _ownership(root: Path, stage: Path, changes: list[dict[str, Any]], original: dict[str, Any],
               simulated: dict[str, Any], capabilities: Any) -> list[dict[str, Any]]:
    registry = capabilities.load_registry()["capabilities"]
    before = _json(root, ".skipo/capabilities.json")
    generated = capabilities.generated_entries(before)
    findings = simulated.get("findings", [])
    retire = {
        (f.get("capability"), f.get("path")) for f in findings
        if f.get("classification") == "retire" and f.get("patterns")
    }
    desired: dict[str, tuple[str, bytes]] = {}
    for cap_id, spec in sorted(registry.items()):
        for item in spec.get("generated", []):
            path = item["path"]
            relative_path(path)
            value = item["content"].encode("utf-8")
            if path in desired and desired[path] != (cap_id, value):
                raise UnsafeRepair(f"Ambiguous generator ownership: {path}")
            desired[path] = (cap_id, value)
    permitted_retire = {
        path for cap_id, path in retire
        if cap_id in registry and path in registry[cap_id].get("safeRetire", [])
    }
    package_before = _json(root, "package.json")
    package_after = _json(stage, "package.json")
    # package.json is application-owned except for *registry-declared* dependencies.
    old_deps = package_before.get("dependencies", {})
    new_deps = package_after.get("dependencies", {})
    if not isinstance(old_deps, dict) or not isinstance(new_deps, dict):
        raise UnsafeRepair("Invalid dependency sections")
    if {k: v for k, v in package_before.items() if k != "dependencies"} != {
        k: v for k, v in package_after.items() if k != "dependencies"
    }:
        raise UnsafeRepair("Migration attempted to change application-owned package metadata")
    canonical_deps: dict[str, set[str]] = {}
    for capability_id in {**before.get("installed", {}), **_json(stage, ".skipo/capabilities.json").get("installed", {})}:
        spec = registry.get(capability_id)
        if not spec:
            raise UnsafeRepair(f"Unknown capability: {capability_id}")
        for name, version in spec.get("dependencies", {}).items():
            canonical_deps.setdefault(name, set()).add(version)
    changed_deps = sorted(k for k in set(old_deps) | set(new_deps) if old_deps.get(k) != new_deps.get(k))
    for dep in changed_deps:
        if new_deps.get(dep) not in canonical_deps.get(dep, set()) or len(canonical_deps[dep]) != 1:
            raise UnsafeRepair(f"Dependency change has no unambiguous canonical owner: {dep}")
    before_dep_state = _json(root, ".skipo/dependencies.json")
    for dep in changed_deps:
        prior = before_dep_state.get(dep)
        if old_deps.get(dep) is not None and prior not in (old_deps.get(dep), new_deps.get(dep)):
            raise UnsafeRepair(f"Unowned dependency range: {dep}")
    for change in changes:
        path = change["path"]
        previous = original.get(path)
        target = simulated.get("_after", {}).get(path)
        if path in STATE_FILES:
            change["owner"] = "skipo-state" if path != "package.json" else "skipo-canonical-dependency"
            if path == "package.json" and not changed_deps:
                raise UnsafeRepair("Unexplained package.json change")
            continue
        if path in desired and target is not None:
            owner, value = desired[path]
            if target["sha256"] != digest(value):
                raise UnsafeRepair(f"Generated output deviates from registry: {path}")
            entry = generated.get(path)
            if previous is not None and (
                not isinstance(entry, dict) or entry.get("owner") != "skipo"
                or entry.get("capability") not in (None, owner)
                or entry.get("checksum") != previous["sha256"]
            ):
                raise UnsafeRepair(f"Unowned/modified generated file: {path}")
            change["owner"] = f"skipo:{owner}"
            continue
        if path in permitted_retire and previous is not None and target is None:
            change["owner"] = "skipo:explicit-safe-retire"
            continue
        # In particular: do not delete unknown children of old module directories.
        raise UnsafeRepair(f"Application-owned or ambiguous path would be modified: {path}")
    return changes


def _fsync_directory(path: Path) -> None:
    try:
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0))
    except OSError:
        return
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def _write_sync(path: Path, data: bytes, mode: int = 0o600) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, mode)
    with os.fdopen(fd, "wb") as file:
        file.write(data)
        file.flush()
        os.fsync(file.fileno())
    _fsync_directory(path.parent)


def _assert_original(root: Path, path: str, expected: dict[str, Any] | None) -> None:
    file = checked(root, path)
    if expected is None:
        if file.exists():
            raise UnsafeRepair(f"Stale plan, new file at {path}")
    elif not file.is_file() or {
        "sha256": digest(file.read_bytes()), "size": file.stat().st_size,
        "mode": stat.S_IMODE(file.stat().st_mode)
    } != expected:
        raise UnsafeRepair(f"Stale or changed file: {path}")


def _install(root: Path, work: Path, change: dict[str, Any], after: dict[str, Any],
             created_dirs: list[Path]) -> None:
    path = change["path"]
    dest = checked(root, path)
    _assert_original(root, path, change["before"])
    if change["after"] is None:
        dest.unlink()
    else:
        missing: list[Path] = []
        parent = dest.parent
        while not parent.exists() and parent != root:
            missing.append(parent)
            parent = parent.parent
        checked(root, path)  # refuse any late symlink in ancestors
        for directory in reversed(missing):
            directory.mkdir()
            created_dirs.append(directory)
        candidate = work / "staged" / path
        # Candidate bytes were frozen and checked during preflight.
        if digest(candidate.read_bytes()) != after[path]["sha256"]:
            raise UnsafeRepair(f"Staged bytes changed: {path}")
        os.chmod(candidate, after[path]["mode"])
        os.replace(candidate, dest)
    _fsync_directory(dest.parent)


def _restore(root: Path, work: Path, changes: list[dict[str, Any]],
             before: dict[str, Any], created_dirs: list[Path]) -> dict[str, Any]:
    errors: list[str] = []
    for change in reversed(changes):
        path = change["path"]
        try:
            dest = checked(root, path)
            prior = change["before"]
            if prior is None:
                if dest.is_file():
                    dest.unlink()
            else:
                dest.parent.mkdir(parents=True, exist_ok=True)
                backup = work / "backups" / path
                if digest(backup.read_bytes()) != prior["sha256"]:
                    raise UnsafeRepair(f"Journal backup corruption: {path}")
                fd, temp = tempfile.mkstemp(prefix=".skipo-restore-", dir=dest.parent)
                try:
                    with os.fdopen(fd, "wb") as stream:
                        stream.write(backup.read_bytes())
                        stream.flush()
                        os.fsync(stream.fileno())
                    os.chmod(temp, prior["mode"])
                    os.replace(temp, dest)
                finally:
                    if os.path.exists(temp):
                        os.unlink(temp)
            _fsync_directory(dest.parent)
        except Exception as exc:
            errors.append(f"{path}: {type(exc).__name__}: {exc}")
    for directory in reversed(created_dirs):
        try:
            directory.rmdir()  # only remove directories introduced by this transaction
        except OSError:
            pass
    try:
        if inventory(root) != before:
            errors.append("Post-rollback inventory differs from exact input state")
    except Exception as exc:
        errors.append(f"Post-rollback inventory failed: {exc}")
    return {"status": "failed" if errors else "restored", "errors": errors}


def transact(root: Path, apply: bool, version: str, simulate: Callable[..., dict[str, Any]],
             capabilities: Any, *, expected_plan_id: str | None = None,
             fault_at: str | None = None) -> dict[str, Any]:
    """Preflight -> simulate -> validate -> journal -> commit -> verify/rollback.

    `simulate` is the pre-existing reconciler, NEVER called on the real root.
    A preview's plan_id may be supplied to reject stale subsequent executions.
    `fault_at` is a deterministic test-only failure hook.
    """
    root = Path(root).absolute()
    receipt: dict[str, Any] = {
        "schemaVersion": 1, "operation": "repair", "ok": False, "applied": False,
        "actions": [], "conflicts": [], "rollback": {"status": "not-needed", "errors": []},
        "verification": {"ok": None, "planned": not apply},
    }
    work: Path | None = None
    journal_created = False
    committed = False
    created_dirs: list[Path] = []
    changes: list[dict[str, Any]] = []
    before: dict[str, Any] = {}
    stage: Path | None = None
    try:
        before = inventory(root)
        if "package.json" not in before:
            raise UnsafeRepair("Target has no package.json")
        _json(root, "package.json")
        # Validate *all* catalogue-controlled paths before running even the
        # sandboxed legacy engine: an unchecked ../ path could escape its copy.
        registry = capabilities.load_registry()["capabilities"]
        managed: set[str] = set()
        for capability, spec in registry.items():
            for entry in spec.get("generated", []):
                relative = entry["path"]
                if relative in managed:
                    raise UnsafeRepair(f"Ambiguous generated ownership: {relative}")
                managed.add(relative)
                parts = relative_path(relative)
                if any(part in IGNORED for part in parts):
                    raise UnsafeRepair(f"Forbidden generated directory: {relative}")
                checked(root, relative)
            for relative in spec.get("safeRetire", []):
                parts = relative_path(relative)
                if any(part in IGNORED for part in parts):
                    raise UnsafeRepair(f"Forbidden retirement directory: {relative}")
                checked(root, relative)
        for relative in capabilities.legacy_migration_paths():
            parts = relative_path(relative)
            if any(part in IGNORED for part in parts):
                raise UnsafeRepair(f"Forbidden legacy migration directory: {relative}")
            checked(root, relative)
        # A dependency migration can rewrite application source. Without a
        # complete canonical ownership proof such a migration is unsupported,
        # and must not execute even in the transaction sandbox.
        from skipo_dependency_migrations import plan_dependency_migrations
        migrations = plan_dependency_migrations(root, version)
        if not migrations.get("ok", False):
            raise UnsafeRepair("Dependency migration preflight: " + "; ".join(migrations.get("errors", [])))
        if migrations.get("migrations"):
            raise UnsafeRepair("Application-source dependency migrations require explicit ownership review")
        work = Path(tempfile.mkdtemp(prefix=".skipo-repair-journal-", dir=root.parent))
        stage = work / "sandbox"
        _copy_project(root, stage)
        if inventory(stage) != before:
            raise UnsafeRepair("Sandbox clone differs from input")
        if fault_at == "during_preflight":
            raise RuntimeError("Injected failure: during_preflight")
        simulation = simulate(stage, apply=True, framework_version=version)
        receipt["findings"] = simulation.get("findings", [])
        receipt["dependency_migrations"] = simulation.get("dependency_migrations", {})
        if not simulation.get("ok"):
            receipt["conflicts"] = simulation.get("conflicts", []) or [
                {"code": "SIMULATION_FAILED", "message": str(simulation.get("verification", {}).get("errors") or simulation.get("update", {}).get("errors") or "Canonical simulation failed")}
            ]
            receipt["verification"] = simulation.get("verification", {"ok": False})
            return receipt
        after = inventory(stage)
        changed_paths = sorted(k for k in before.keys() | after.keys() if before.get(k) != after.get(k))
        changes = [{"path": p, "before": before.get(p), "after": after.get(p),
                    "action": "delete" if p not in after else ("create" if p not in before else "update")}
                   for p in changed_paths]
        # Store file state in one stable, comparable plan, not mutable path objects.
        _ownership(root, stage, changes, before, {"_after": after, **simulation}, capabilities)
        plan_payload = {"version": version, "inputs": before, "actions": changes,
                        "registry_sha256": digest(canonical(capabilities.load_registry())),
                        "migration_paths": capabilities.legacy_migration_paths()}
        plan_id = digest(canonical(plan_payload))
        receipt.update({"plan_id": plan_id, "inputs": before, "actions": changes,
                        "expected_results": after, "evidence": {"preflight": "passed", "simulation": simulation.get("verification", {})}})
        if expected_plan_id is not None and expected_plan_id != plan_id:
            raise UnsafeRepair("STALE_PLAN: input, policy or planned output differs from preview")
        if not apply:
            receipt.update({"ok": True, "verification": {"ok": None, "planned": True}})
            return receipt
        if not changes:
            receipt.update({"ok": True, "noop": True, "verification": capabilities.verify(root)})
            receipt["ok"] = bool(receipt["verification"].get("ok"))
            return receipt
        if inventory(root) != before:
            raise UnsafeRepair("STALE_PLAN: project changed during preflight")
        # Durable write-ahead journal: backups, desired bytes, and manifest
        # are fsynced before the first application mutation.
        for change in changes:
            path = change["path"]
            if change["before"] is not None:
                content = checked(root, path).read_bytes()
                if digest(content) != change["before"]["sha256"]:
                    raise UnsafeRepair(f"STALE_PLAN: {path}")
                _write_sync(work / "backups" / path, content)
            if change["after"] is not None:
                content = checked(stage, path).read_bytes()
                if digest(content) != change["after"]["sha256"]:
                    raise UnsafeRepair(f"Invalid staged result: {path}")
                _write_sync(work / "staged" / path, content)
        _write_sync(work / "manifest.json", canonical({"schemaVersion": 1, "plan_id": plan_id,
                    "inputs": before, "actions": changes, "status": "prepared"}))
        _fsync_directory(work)
        journal_created = True
        if fault_at == "after_journal":
            raise RuntimeError("Injected failure: after_journal")
        for index, change in enumerate(changes):
            if fault_at == f"before_write:{index}":
                raise RuntimeError(f"Injected failure: before_write:{index}")
            _install(root, work, change, after, created_dirs)
            committed = True
            if fault_at == f"after_write:{index}":
                raise RuntimeError(f"Injected failure: after_write:{index}")
        if fault_at == "before_verify":
            raise RuntimeError("Injected failure: before_verify")
        actual = inventory(root)
        if actual != after:
            raise UnsafeRepair("Post-commit inventory differs from staged expected state")
        verification = capabilities.verify(root)  # independent, released/main verifier
        receipt["verification"] = verification
        if not verification.get("ok"):
            raise UnsafeRepair("Independent capability verification failed")
        if fault_at == "after_verify":
            raise RuntimeError("Injected failure: after_verify")
        receipt.update({"ok": True, "applied": True, "rollback": {"status": "not-needed", "errors": []}})
        return receipt
    except Exception as exc:
        receipt["conflicts"].append({"code": "REPAIR_TRANSACTION_FAILED", "message": f"{type(exc).__name__}: {exc}"})
        if journal_created and work is not None:
            receipt["rollback"] = _restore(root, work, changes, before, created_dirs)
        if receipt["rollback"]["status"] == "failed":
            receipt["journal"] = str(work)
            receipt["conflicts"].append({"code": "ROLLBACK_INCOMPLETE", "message": "Retained journal for manual restoration"})
        receipt["verification"] = {"ok": False, "errors": [str(exc)], "independent": receipt["verification"]}
        return receipt
    finally:
        # A failed rollback deliberately retains the durable recovery journal.
        if work is not None and receipt["rollback"]["status"] != "failed":
            shutil.rmtree(work, ignore_errors=True)
